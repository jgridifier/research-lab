/* Research Lab front page. Renders docs/stories.json.
   To add a story, add one entry to that file — do not edit this file. */
(function () {
  "use strict";

  var MONTHS = [
    "January", "February", "March", "April", "May", "June",
    "July", "August", "September", "October", "November", "December"
  ];
  var DAYS = ["Sunday", "Monday", "Tuesday", "Wednesday", "Thursday", "Friday", "Saturday"];

  function pad(n) { return n < 10 ? "0" + n : "" + n; }

  function todayParts() {
    // America/New_York — the box and Jared are on this zone.
    var fmt = new Intl.DateTimeFormat("en-US", {
      timeZone: "America/New_York",
      weekday: "long", year: "numeric", month: "long", day: "numeric"
    });
    var parts = { weekday: "", month: "", day: "", year: "" };
    fmt.formatToParts(new Date()).forEach(function (p) {
      if (p.type === "weekday") parts.weekday = p.value;
      if (p.type === "month") parts.month = p.value;
      if (p.type === "day") parts.day = p.value;
      if (p.type === "year") parts.year = p.value;
    });
    return parts;
  }

  function fmtDate(iso) {
    if (!iso) return "";
    var m = /^(\d{4})-(\d{2})-(\d{2})/.exec(iso);
    if (!m) return iso;
    var month = MONTHS[parseInt(m[2], 10) - 1] || m[2];
    return month + " " + parseInt(m[3], 10) + ", " + m[1];
  }

  function fmtDateShort(iso) {
    if (!iso) return "";
    var m = /^(\d{4})-(\d{2})-(\d{2})/.exec(iso);
    if (!m) return iso;
    var month = (MONTHS[parseInt(m[2], 10) - 1] || "").slice(0, 3);
    return month + " " + parseInt(m[3], 10) + ", " + m[1];
  }

  function esc(s) {
    return String(s == null ? "" : s)
      .replace(/&/g, "&amp;")
      .replace(/</g, "&lt;")
      .replace(/>/g, "&gt;")
      .replace(/"/g, "&quot;");
  }

  function marks(story) {
    var h = "";
    if (story.external) {
      var label = story.kind === "repo" ? "External · GitHub" : "External · Pages";
      if (story.kind === "site" && story.section === "other-sites") label = "External · Site";
      h += '<span class="ext-mark">' + label + "</span>";
    }
    return h;
  }

  function sectionName(data, id) {
    var s = (data.sections || []).filter(function (x) { return x.id === id; })[0];
    return s ? s.name : id;
  }

  function storyHref(story) {
    return story.url;
  }

  function byline(story, data) {
    var bits = [];
    if (story.kicker) bits.push(esc(story.kicker));
    else bits.push(esc(sectionName(data, story.section)));
    bits.push(esc(fmtDate(story.date)));
    return bits.join(" · ") + " " + marks(story);
  }

  function renderLead(story, data) {
    if (!story) return "";
    return (
      '<article class="lead">' +
        '<p class="kicker">' + esc(story.kicker || sectionName(data, story.section)) + "</p>" +
        "<h2><a href=\"" + esc(storyHref(story)) + "\">" + esc(story.title) + "</a></h2>" +
        '<p class="dek">' + esc(story.dek) + "</p>" +
        '<p class="byline">' + byline(story, data) + "</p>" +
      "</article>"
    );
  }

  function renderStory(story, data, level) {
    var H = level || "h3";
    return (
      '<article class="story">' +
        '<p class="kicker">' + esc(story.kicker || sectionName(data, story.section)) + "</p>" +
        "<" + H + "><a href=\"" + esc(storyHref(story)) + "\">" + esc(story.title) + "</a></" + H + ">" +
        '<p class="dek">' + esc(story.dek) + "</p>" +
        '<p class="byline">' + byline(story, data) + "</p>" +
      "</article>"
    );
  }

  function renderLatest(stories, data) {
    var items = stories.slice().sort(function (a, b) {
      if (a.date === b.date) return a.title.localeCompare(b.title);
      return a.date < b.date ? 1 : -1;
    }).slice(0, 10);
    var h = '<aside class="latest" aria-labelledby="latest-h"><h2 id="latest-h">Latest</h2><ol>';
    items.forEach(function (s) {
      h += "<li><a href=\"" + esc(storyHref(s)) + "\">" +
        '<span class="when">' + esc(fmtDateShort(s.date)) + " · " + esc(s.kicker || sectionName(data, s.section)) +
        (s.external ? " · External" : "") + "</span>" +
        '<span class="hl">' + esc(s.title) + "</span></a></li>";
    });
    return h + "</ol></aside>";
  }

  function kindLabel(story) {
    if (story.external && story.kind === "repo") return "GitHub repo";
    if (story.external && story.kind === "site") return "Pages site";
    var map = {
      review: "Review", scout: "Scout", track: "Track", results: "Results",
      teaching: "Teaching", learning: "Learning", program: "Programme",
      page: "Page", note: "Note"
    };
    return map[story.kind] || "Page";
  }

  function renderIndex(stories, data, filter) {
    var q = (filter.q || "").trim().toLowerCase();
    var sec = filter.section || "all";
    var type = filter.type || "all";
    var list = stories.filter(function (s) {
      if (sec !== "all" && s.section !== sec) return false;
      if (type === "internal" && s.external) return false;
      if (type === "external" && !s.external) return false;
      if (q) {
        var hay = (s.title + " " + (s.dek || "") + " " + (s.kicker || "") + " " + sectionName(data, s.section) + " " + (s.kind || "")).toLowerCase();
        if (hay.indexOf(q) === -1) return false;
      }
      return true;
    });
    list.sort(function (a, b) {
      if (a.date === b.date) return a.title.localeCompare(b.title);
      return a.date < b.date ? 1 : -1;
    });

    var countEl = document.getElementById("index-count");
    if (countEl) {
      countEl.textContent = list.length + " stor" + (list.length === 1 ? "y" : "ies");
    }

    if (!list.length) {
      return '<p class="empty">No stories match those filters. Clear the search or choose All.</p>';
    }

    // Group by section, preserving section order in the data file, then any leftovers.
    var groups = [];
    var seen = {};
    (data.sections || []).forEach(function (secdef) {
      var items = list.filter(function (s) { return s.section === secdef.id; });
      if (items.length) {
        groups.push({ def: secdef, items: items });
        seen[secdef.id] = true;
      }
    });
    var leftovers = list.filter(function (s) { return !seen[s.section]; });
    if (leftovers.length) groups.push({ def: { id: "other", name: "Other", blurb: "" }, items: leftovers });

    var h = "";
    groups.forEach(function (g) {
      h += '<section class="index-section" aria-labelledby="ix-' + esc(g.def.id) + '">';
      h += "<h3 id=\"ix-" + esc(g.def.id) + "\">" + esc(g.def.name) + "</h3>";
      if (g.def.blurb && sec === "all" && !q) {
        h += '<p class="blurb">' + esc(g.def.blurb) + "</p>";
      }
      h += '<ul class="index-list">';
      g.items.forEach(function (s) {
        h += "<li>" +
          '<div class="meta">' + esc(fmtDateShort(s.date)) + "</div>" +
          "<div>" +
            '<a class="hl" href="' + esc(storyHref(s)) + '">' + esc(s.title) +
              '<span class="dek-s">' + esc(s.dek) + "</span></a>" +
          "</div>" +
          '<div class="marks">' +
            '<span class="kind-mark">' + esc(kindLabel(s)) + "</span>" +
            marks(s) +
          "</div>" +
        "</li>";
      });
      h += "</ul></section>";
    });
    return h;
  }

  function populateFilters(data) {
    var sel = document.getElementById("filter-section");
    if (!sel) return;
    var opts = '<option value="all">All sections</option>';
    (data.sections || []).forEach(function (s) {
      opts += '<option value="' + esc(s.id) + '">' + esc(s.name) + "</option>";
    });
    sel.innerHTML = opts;
  }

  function renderNav(data) {
    var nav = document.getElementById("secnav");
    if (!nav) return;
    // Main research sections + Index. "Other Research" / "Other Sites" live in the Index.
    var main = (data.sections || []).filter(function (s) {
      return s.id !== "other-research" && s.id !== "other-sites";
    });
    var html = "";
    main.forEach(function (s) {
      html += '<a href="#section-' + esc(s.id) + '">' + esc(s.nav || s.name) + "</a>";
    });
    html += '<a href="#index">Index</a>';
    nav.innerHTML = html;
  }

  function sectionAnchorTargets(data, stories) {
    // Each nav item jumps to the first featured/latest story of that section in the index,
    // or to a dedicated front-page block if present.
    // We add hidden anchors at the index groups; also honour #section-X by scrolling to the index group.
  }

  function boot(data) {
    var stories = data.stories || [];
    var lead = stories.filter(function (s) { return s.featured === "lead"; })[0] || stories[0];
    var secondaries = stories.filter(function (s) { return s.featured === "secondary"; });
    // Beside the lead: first two. The rest go in the "also" row.
    var beside = secondaries.slice(0, 2);
    var also = secondaries.slice(2);

    var front = document.getElementById("front");
    var html = renderLead(lead, data);
    html += '<div class="secondaries">' + beside.map(function (s) { return renderStory(s, data); }).join("") + "</div>";
    html += renderLatest(stories, data);
    if (also.length) {
      html += '<section class="also" aria-label="Also in this edition"><h2>Also in this edition</h2><div class="also-grid">' +
        also.map(function (s) { return renderStory(s, data); }).join("") + "</div></section>";
    }
    front.innerHTML = html;

    // Dateline
    var t = todayParts();
    var dateEl = document.getElementById("mast-date");
    if (dateEl) dateEl.textContent = t.weekday + ", " + t.month + " " + t.day + ", " + t.year;
    var yearEl = document.getElementById("mast-year");
    if (yearEl) yearEl.textContent = t.year;
    var nEl = document.getElementById("story-total");
    if (nEl) nEl.textContent = stories.length + " stories";

    renderNav(data);
    populateFilters(data);

    var state = { q: "", section: "all", type: "all" };
    var indexBody = document.getElementById("index-body");

    function refreshIndex() {
      indexBody.innerHTML = renderIndex(stories, data, state);
    }
    refreshIndex();

    var search = document.getElementById("filter-q");
    var secSel = document.getElementById("filter-section");
    if (search) {
      search.addEventListener("input", function () {
        state.q = search.value;
        refreshIndex();
      });
    }
    if (secSel) {
      secSel.addEventListener("change", function () {
        state.section = secSel.value;
        refreshIndex();
      });
    }
    document.querySelectorAll("#type-chips .chip").forEach(function (btn) {
      btn.addEventListener("click", function () {
        state.type = btn.getAttribute("data-type") || "all";
        document.querySelectorAll("#type-chips .chip").forEach(function (b) {
          b.setAttribute("aria-pressed", b === btn ? "true" : "false");
        });
        refreshIndex();
      });
    });

    // Section nav: Banking etc. jump to that group in the Index, and set the filter
    // so the section is easy to read. #index just scrolls.
    document.getElementById("secnav").addEventListener("click", function (ev) {
      var a = ev.target.closest("a");
      if (!a) return;
      var href = a.getAttribute("href") || "";
      var m = /^#section-(.+)$/.exec(href);
      if (m) {
        ev.preventDefault();
        state.section = m[1];
        state.q = "";
        if (search) search.value = "";
        if (secSel) secSel.value = m[1];
        refreshIndex();
        var target = document.getElementById("index");
        if (target) target.scrollIntoView({ behavior: "smooth", block: "start" });
        history.replaceState(null, "", href);
      }
      document.querySelectorAll("#secnav a").forEach(function (x) {
        x.setAttribute("aria-current", x === a ? "true" : "false");
      });
    });

    // Honour a deep link on load.
    var hash = (location.hash || "").replace(/^#/, "");
    var sm = /^section-(.+)$/.exec(hash);
    if (sm) {
      state.section = sm[1];
      if (secSel) secSel.value = sm[1];
      refreshIndex();
      var t2 = document.getElementById("index");
      if (t2) setTimeout(function () { t2.scrollIntoView({ behavior: "smooth", block: "start" }); }, 50);
    }
  }

  function fail(msg) {
    var el = document.getElementById("front");
    if (el) {
      el.innerHTML = '<p class="err">' + esc(msg) + "</p>";
    }
  }

  var src = "stories.json";
  fetch(src, { cache: "no-cache" })
    .then(function (r) {
      if (!r.ok) throw new Error("Could not load " + src + " (" + r.status + ").");
      return r.json();
    })
    .then(boot)
    .catch(function (err) {
      fail("The front page is driven by stories.json and needs to be served over HTTP. From the docs/ folder run: python -m http.server 8000 — then open http://localhost:8000/. (" + (err && err.message ? err.message : err) + ")");
    });
})();
